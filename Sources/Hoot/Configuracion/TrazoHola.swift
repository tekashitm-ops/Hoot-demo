    var animatableData: CGFloat {
        get { progreso }
        set { progreso = newValue }
    }

    static let proporcion: CGFloat = 3.0746

    static let grosor: CGFloat = 0.0980

    func path(in r: CGRect) -> Path {
        guard progreso > 0.002 else { return Path() }
        let alto = min(r.height, r.width / Self.proporcion)
        let origen = CGPoint(x: r.midX - alto * Self.proporcion / 2, y: r.midY - alto / 2)
        let base = Self.camino(origen: origen, alto: alto)
        let trozo = progreso >= 1 ? base : base.trimmedPath(from: 0, to: progreso)

        let contorno = trozo.strokedPath(StrokeStyle(lineWidth: Self.grosor * alto, lineCap: .round, lineJoin: .round))
        return Path(contorno.cgPath.normalized())
    }

    static func camino(origen: CGPoint, alto: CGFloat) -> Path {
        let p = puntos.map { CGPoint(x: origen.x + $0.x * alto, y: origen.y + $0.y * alto) }
        var camino = Path()
        guard p.count > 1 else { return camino }
        camino.move(to: p[0])
        for i in 0..<(p.count - 1) {
            let p0 = p[max(i - 1, 0)], p1 = p[i], p2 = p[i + 1], p3 = p[min(i + 2, p.count - 1)]
            let c1 = CGPoint(x: p1.x + (p2.x - p0.x) / 6, y: p1.y + (p2.y - p0.y) / 6)
            let c2 = CGPoint(x: p2.x - (p3.x - p1.x) / 6, y: p2.y - (p3.y - p1.y) / 6)
            camino.addCurve(to: p2, control1: c1, control2: c2)
        }
        return camino
    }

